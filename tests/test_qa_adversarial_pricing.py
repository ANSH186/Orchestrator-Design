@pytest.mark.parametrize(
    "case,category,supplier,quantity,round_number,message,expected_price,expected_label",
    MESSAGE_CASES,
    ids=[case[0] for case in MESSAGE_CASES],
)
def test_adversarial_message_pricing(
    kb, case, category, supplier, quantity, round_number, message,
    expected_price, expected_label
):
    _, state = run_graph(
        kb,
        category=category,
        supplier=supplier,
        quantity=quantity,
        round_number=round_number,
        message=message,
    )
    assert state["final_label"] == expected_label, (
        f"{case}: got {state['final_label']} for {message!r}"
    )
    pricing = state.get("pricing")
    if expected_price is None:
        assert pricing is None or pricing.normalized_price is None
    else:
        assert pricing is not None
        assert pricing.normalized_price == expected_price


MULTIPLE_PRICE_CASES = [
    (
        "same_line_list_then_offer",
        "Our list price is INR 20,000 per monitor, but we can offer INR 10,000 per monitor.",
    ),
    (
        "list_line_then_offer",
        "Our list price is INR 20,000 per monitor.\nWe can offer INR 10,000 per monitor.",
    ),
    (
        "order_value_then_offer",
        "The order value is INR 5,00,000.\nWe can offer INR 10,000 per monitor.",
    ),
    (
        "liability_cap_then_offer",
        "Liability is capped at INR 5,00,000.\nWe can offer INR 10,000 per monitor.",
    ),
    (
        "budget_then_offer",
        "The total budget is INR 5,00,000 for this order.\nWe can offer INR 10,000 per monitor.",
    ),
]


@pytest.mark.parametrize("case,message", MULTIPLE_PRICE_CASES, ids=[c[0] for c in MULTIPLE_PRICE_CASES])
def test_multiple_prices_select_actual_offer(kb, case, message):
    _, state = run_graph(
        kb,
        category="monitors",
        supplier="Coastline Caterers",
        quantity=10,
        round_number=1,
        message=message,
    )
    assert state["final_label"] == "ACCEPT:ACCEPTABLE_PRICE:"
    assert state["pricing"].normalized_price == Decimal("10000")


def test_previous_quote_total_basis_is_not_double_converted(kb):
    message = (
        "[Earlier message — Coastline Caterers, 2026-09-30]\n"
        "The total price is INR 3,000 in total for all 5 monitors.\n\n"
        "[Latest message — Coastline Caterers, 2026-10-01]\n"
        "We can do a further 10% off our previous quote."
    )
    _, state = run_graph(
        kb,
        category="monitors",
        supplier="Coastline Caterers",
        quantity=5,
        round_number=1,
        message=message,
    )
    assert state["pricing"].normalized_price == Decimal("540")
    assert state["final_label"] == "ACCEPT:ACCEPTABLE_PRICE:"


def test_concession_independent_values():
    assert acceptable_price(
        target=Decimal("100"), walkaway=Decimal("200"), rounds=3,
        round_number=1, beta=Decimal("1"),
    ) == Decimal("100")
    assert acceptable_price(
        target=Decimal("100"), walkaway=Decimal("200"), rounds=3,
        round_number=2, beta=Decimal("1"),
    ) == Decimal("150")
    assert acceptable_price(
        target=Decimal("100"), walkaway=Decimal("200"), rounds=3,
        round_number=3, beta=Decimal("1"),
    ) == Decimal("200")
    assert acceptable_price(
        target=Decimal("100"), walkaway=Decimal("200"), rounds=3,
        round_number=2, beta=Decimal("2"),
    ) == Decimal("125")
    assert acceptable_price(
        target=Decimal("100"), walkaway=Decimal("200"), rounds=3,
        round_number=2, beta=Decimal("1"),
        probation=True,
    ) == Decimal("100")


def test_boundary_and_rounding_independent():
    level = Decimal("100.5")
    assert round_half_up_int(level) == 101
    assert round_half_up_int(Decimal("100.49")) == 100
    assert approval_amount(Decimal("100"), 10) == Decimal("1000")
    assert approval_amount(Decimal("100.01"), 10) == Decimal("1000.10")


