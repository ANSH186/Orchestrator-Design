def run_graph(kb, *, category, supplier="Coastline Caterers", quantity=10,
              round_number=1, message, thread_date=date(2026, 10, 1)):
    thread = make_thread(
        thread_id="QA-CASE",
        category=category,
        supplier=supplier,
        quantity=quantity,
        round_number=round_number,
        message=message,
        thread_date=thread_date,
    )
    state = ProcurementGraph(kb, run_id="qa-adversarial").run(thread)
    return thread, state


